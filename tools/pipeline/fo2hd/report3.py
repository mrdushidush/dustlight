"""Phase 3 report (PLAN.md P3.5): one local HTML page.

Collects the GPU map test summaries (tools/scripts/map_test.ps1 ->
<data_root>/reports/map/summary-*.json), the presentation benchmarks
(present_bench.ps1 -> <data_root>/reports/present/bench-*.csv), the stills
(phase3_stills.ps1 -> <data_root>/reports/phase3/img/) and reruns the Python
replay on the stress captures. Writes <data_root>/reports/phase3/index.html.
Game-derived images: keep it local, never commit or publish it.
"""

from __future__ import annotations

import csv
import html
import json
from pathlib import Path

from . import capture as capture_mod
from .config import Paths
from .dat import GameFiles
from .replay import replay

OPS = ["fill", "lit", "floor", "interface", "text", "translucent", "egg", "outline"]
VARIANT_TITLES = {
    "sdl": "original SDL path",
    "d3d11": "D3D11 presenter (Phase 2)",
    "map": "D3D11 + GPU map (Phase 3)",
}


def _load_json(path: Path) -> dict:
    # PowerShell writes UTF-8 with a BOM.
    return json.loads(path.read_text(encoding="utf-8-sig")) if path.exists() else {}


def _load_bench(path: Path) -> dict[str, float]:
    if not path.exists():
        return {}
    rows: dict[str, list[float]] = {}
    with path.open(encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            rows.setdefault(row["Variant"], []).append(float(row["MsPerFrame"]))
    return {k: sum(v) / len(v) for k, v in rows.items()}


def build(paths: Paths, files: GameFiles, notes: dict) -> Path:
    reports = paths.reports
    out = reports / "phase3"
    (out / "img").mkdir(parents=True, exist_ok=True)

    summaries = [_load_json(p) for p in sorted((reports / "map").glob("summary-*.json"))]
    benches = {name: _load_bench(reports / "present" / f"bench-{name}.csv") for name in ("walk", "stress")}

    replay_rows = []
    for capture_path in sorted(paths.captures.glob("maptest_*.json")):
        cap = capture_mod.load(capture_path)
        result = replay(cap, files)
        modes = sorted({d.get("mode") for d in cap.draws if d.get("op") == "object" and d.get("mode") not in (None, "normal")})
        replay_rows.append((capture_path.stem, result.diff_pixels, len(cap.draws), modes))

    e = html.escape
    parts = [
        "<!doctype html><html><head><meta charset='utf-8'><title>Phase 3 report</title><style>",
        ":root{--bg:#1b1a17;--panel:#25231f;--ink:#e4dfd4;--dim:#a39d90;--accent:#d8a14a;--ok:#8fd18a;--bad:#e27d6a}",
        "body{background:var(--bg);color:var(--ink);font:15px/1.5 system-ui,sans-serif;margin:0 auto;max-width:1400px;padding:16px}",
        "h1{font-size:26px;margin:8px 0}h2{font-size:20px;margin:32px 0 8px;color:var(--accent)}h3{font-size:16px;margin:18px 0 6px}",
        ".box{background:var(--panel);border-radius:8px;padding:12px 16px;margin:12px 0}",
        "table{border-collapse:collapse;margin:8px 0}td,th{border-bottom:1px solid #3a372f;padding:4px 10px;text-align:left;vertical-align:top}",
        "th{color:var(--dim);font-weight:600}.num{text-align:right;font-variant-numeric:tabular-nums}",
        ".ok{color:var(--ok)}.bad{color:var(--bad)}.dim{color:var(--dim)}",
        ".cmp{position:relative;display:inline-block;max-width:100%;--pos:50%;user-select:none}",
        ".cmp img{display:block;max-width:100%}",
        ".cmp img.top{position:absolute;inset:0;clip-path:inset(0 0 0 var(--pos))}",
        ".cmp .bar{position:absolute;top:0;bottom:0;left:var(--pos);width:2px;background:var(--accent);pointer-events:none}",
        ".cmp input{position:absolute;inset:0;width:100%;height:100%;opacity:0;cursor:ew-resize;margin:0}",
        ".tags{position:absolute;top:6px;left:8px;right:8px;display:flex;justify-content:space-between;pointer-events:none;font-size:12px}",
        ".tags span{background:#000a;padding:2px 6px;border-radius:4px}",
        ".pair{display:flex;gap:12px;flex-wrap:wrap}.pair figure{flex:1 1 560px;margin:0}.pair img{width:100%}",
        "figcaption{color:var(--dim);font-size:13px;margin-top:4px}",
        "</style></head><body>",
        "<h1>Dustlight — Phase 3: the map drawn on the GPU</h1>",
        f"<p class='dim'>Generated by <code>fo2hd report3</code> from the automated test runs. {e(notes.get('generated', ''))}</p>",
        "<div class='box'><b>What I need from you</b><ul>",
    ]
    for item in notes.get("decisions", []):
        parts.append(f"<li>{item}</li>")
    parts.append("</ul></div>")

    parts.append("<h2>What Phase 3 built</h2>")
    for line in notes.get("summary", []):
        parts.append(f"<p>{line}</p>")

    if (out / "img" / "map.png").exists():
        parts.append("<h2>What it looks like</h2>")
        parts.append("<p>Your save game at 3440×1440, scale 3 (1146×480 game pixels), drawn by the new path. Drag across the image: left is the map as it looks "
                     "(the same pixels the original draws), right is the <b>tinted debug view</b> (Ctrl+F9 in game): every pixel the GPU map supplies is tinted cyan. "
                     "The interface bar, windows and the mouse cursor stay with the game's own drawing.</p>")
        parts.append(
            "<div class='cmp'><img src='img/map.png' alt='map'><img class='top' src='img/tint.png' alt='tinted'><div class='bar'></div>"
            "<div class='tags'><span>as it looks</span><span>tinted: GPU-drawn pixels</span></div>"
            "<input type='range' min='0' max='100' value='50' oninput=\"this.parentNode.style.setProperty('--pos',this.value+'%')\"></div>"
        )
        parts.append("<div class='pair'>"
                     "<figure><img src='img/inventory.png'><figcaption>Inventory open over the map (tinted view): the GPU map stops exactly at the window's edge.</figcaption></figure>"
                     "<figure><img src='img/options.png'><figcaption>Options menu (tinted view): the menu and the cursor are the game's own pixels.</figcaption></figure>"
                     "</div>")

    parts.append("<h2>Exactness checks</h2>")
    parts.append("<p>Every 1.5 s during each run the game redraws the map the original way and checks four things: "
                 "<b>1×</b> the GPU map has exactly the palette indices of the original map window; "
                 "<b>2×/3×/4×</b> the scaled GPU maps are exactly the 1× map with each pixel repeated; "
                 "<b>composite</b> the final frame at 1:1 equals the original presentation; "
                 "<b>mask</b> the GPU map is used on exactly the screen pixels where the game's own window manager shows the map.</p>")
    for s in summaries:
        cls = "ok" if s.get("failed", 1) == 0 else "bad"
        extra = " ".join(s.get("extra") or []) or "the working copy's settings (1280×960 window, scale 2, 640×480 game pixels)"
        parts.append(f"<h3>{e(str(s.get('label')))}: <span class='{cls}'>{s.get('checks', 0)} checks, {s.get('failed', 0)} failed</span></h3>")
        parts.append(f"<p class='dim'>{e(extra)} · {e(str(s.get('when', '')))}</p>")
        parts.append("<table><tr><th>run</th><th class='num'>checks</th><th class='num'>failed</th><th>stress setup</th><th class='num'>live fallback (max px)</th><th>last 1× check</th></tr>")
        for r in s.get("runs", []):
            rc = "ok" if r.get("failed", 1) == 0 else "bad"
            live = r.get("live_max")
            live_text = "" if live is None else f"{live} ({r.get('live_nonzero', 0)}/{r.get('live_samples', 0)})"
            parts.append(f"<tr><td>{e(r['name'])}</td><td class='num'>{r['checks']}</td><td class='num {rc}'>{r['failed']}</td>"
                         f"<td class='dim'>{e(r.get('stress') or '—')}</td><td class='num'>{live_text}</td><td class='dim'>{e(r.get('last_1x') or '')}</td></tr>")
        parts.append("</table>")
        cov = s.get("coverage", {})
        parts.append("<p>1× checks whose frame used each kind of drawing: " + ", ".join(f"{e(op)} <b>{cov.get(op, 0)}</b>" for op in OPS) + ".</p>")

    if replay_rows:
        parts.append("<h3>Cross-check: Python replay of the stress captures</h3>")
        parts.append("<p class='dim'>The Phase 1 replay test (a Python copy of the game's drawing code) on the captures taken at the end of each stress run, "
                     "which include the forced translucency modes.</p><table><tr><th>capture</th><th class='num'>draws</th><th>translucency modes</th><th>result</th></tr>")
        for name, diff, draws, modes in replay_rows:
            cls = "ok" if diff == 0 else "bad"
            parts.append(f"<tr><td>{e(name)}</td><td class='num'>{draws}</td><td>{e(', '.join(modes) or '—')}</td><td class='{cls}'>{diff} px differ</td></tr>")
        parts.append("</table>")

    for line in notes.get("checks_text", []):
        parts.append(f"<p>{line}</p>")

    if any(benches.values()):
        parts.append("<h2>Cost per frame</h2>")
        parts.append("<p>CPU time spent getting each frame to the screen, at 3440×1440 scale 3, frames capped at 60 fps by the game. "
                     "For the GPU map this includes rebuilding the draw list whenever something on the map changed, and any time the CPU waits for the GPU. "
                     "The GPU's own time isn't measured yet (that needs GPU timers).</p>")
        parts.append("<table><tr><th>path</th><th class='num'>save game walk</th><th class='num'>stress (constant scrolling and moving)</th></tr>")
        for variant in ("sdl", "d3d11", "map"):
            w = benches["walk"].get(variant)
            st = benches["stress"].get(variant)
            if w is None and st is None:
                continue
            fmt = lambda v: "—" if v is None else f"{v:.2f} ms"
            parts.append(f"<tr><td>{e(VARIANT_TITLES[variant])}</td><td class='num'>{fmt(w)}</td><td class='num'>{fmt(st)}</td></tr>")
        parts.append("</table>")
        for line in notes.get("cost_text", []):
            parts.append(f"<p>{line}</p>")

    parts.append("<h2>Known gaps</h2><ul>")
    for item in notes.get("gaps", []):
        parts.append(f"<li>{item}</li>")
    parts.append("</ul><h2>What happens next</h2><ul>")
    for item in notes.get("next", []):
        parts.append(f"<li>{item}</li>")
    parts.append("</ul></body></html>")
    (out / "index.html").write_text("\n".join(parts), encoding="utf-8")
    return out / "index.html"
