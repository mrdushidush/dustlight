"""Phase 1 go/no-go report (PLAN.md P1.10): one local HTML page.

Collects the outputs of compose (P1.9), anim (P1.8), bakeoff (P1.6), hdassets
(P1.7 throughput) and artstats, reruns the replay test, and writes
<data_root>/reports/phase1/index.html. The page shows game-derived images, so
it stays local: never commit or publish it.
"""

from __future__ import annotations

import html
import json
import shutil
from pathlib import Path

from . import capture as capture_mod
from .config import Paths
from .dat import GameFiles
from .replay import replay

SCENE_TITLES = {
    "temple_indoor": "Temple of Trials, inside (arcaves.map)",
    "temple_outdoor": "Temple of Trials, outside, noon (artemple.map)",
    "arroyo_day": "Arroyo village, 13:00 (arvillag.map)",
    "newreno_night": "New Reno at night, 23:00 (newr1.map)",
}


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def build(paths: Paths, files: GameFiles, notes: dict) -> Path:
    reports = paths.reports
    out = reports / "phase1"
    img = out / "img"
    img.mkdir(parents=True, exist_ok=True)

    compose = _load(reports / "compose" / "summary.json")
    anim = _load(reports / "anim" / "results.json")
    bakeoff = _load(reports / "bakeoff" / "results.json")
    hd_run = _load(paths.data_root / "hd" / "last_run.json")
    art = _load(paths.data_root / "art_stats.json")

    replay_rows = []
    for capture_path in sorted(paths.captures.glob("*.json")):
        cap = capture_mod.load(capture_path)
        result = replay(cap, files)
        replay_rows.append((capture_path.stem, result.diff_pixels, len(cap.draws)))

    for scene in compose:
        for name in ("original", "hd_orig", "hd_lit", "light", "normals", "orig_equiv"):
            src = reports / "compose" / scene / f"{name}.png"
            if src.exists():
                shutil.copyfile(src, img / f"{scene}_{name}.png")
    for name in ("walk_side_by_side", "walk_original", "walk_hd", "walk_stabilized", "walk_master2x"):
        src = reports / "anim" / f"{name}.gif"
        if src.exists():
            shutil.copyfile(src, img / f"{name}.gif")

    e = html.escape
    parts = [
        "<!doctype html><html><head><meta charset='utf-8'><title>Phase 1 go/no-go</title><style>",
        ":root{--bg:#1b1a17;--panel:#25231f;--ink:#e4dfd4;--dim:#a39d90;--accent:#d8a14a;--ok:#8fd18a;--bad:#e27d6a}",
        "body{background:var(--bg);color:var(--ink);font:15px/1.5 system-ui,sans-serif;margin:0 auto;max-width:1400px;padding:16px}",
        "h1{font-size:26px;margin:8px 0}h2{font-size:20px;margin:32px 0 8px;color:var(--accent)}h3{font-size:16px;margin:18px 0 6px}",
        ".box{background:var(--panel);border-radius:8px;padding:12px 16px;margin:12px 0}",
        "table{border-collapse:collapse;margin:8px 0}td,th{border-bottom:1px solid #3a372f;padding:4px 10px;text-align:left}",
        "th{color:var(--dim);font-weight:600}.num{text-align:right;font-variant-numeric:tabular-nums}",
        ".ok{color:var(--ok)}.bad{color:var(--bad)}.dim{color:var(--dim)}",
        ".cmp{position:relative;display:inline-block;max-width:100%;--pos:50%;user-select:none}",
        ".cmp img{display:block;max-width:100%;image-rendering:auto}",
        ".cmp img.top{position:absolute;inset:0;clip-path:inset(0 0 0 var(--pos))}",
        ".cmp .bar{position:absolute;top:0;bottom:0;left:var(--pos);width:2px;background:var(--accent);pointer-events:none}",
        ".cmp input{position:absolute;inset:0;width:100%;height:100%;opacity:0;cursor:ew-resize;margin:0}",
        ".tags{position:absolute;top:6px;left:8px;right:8px;display:flex;justify-content:space-between;pointer-events:none;font-size:12px}",
        ".tags span{background:#000a;padding:2px 6px;border-radius:4px}",
        ".btns button{background:#332f28;color:var(--ink);border:1px solid #4a453b;border-radius:4px;padding:3px 10px;margin:4px 4px 0 0;cursor:pointer}",
        ".btns button.on{border-color:var(--accent);color:var(--accent)}",
        ".thumbs img{max-width:32%;margin-right:1%}",
        "</style></head><body>",
        "<h1>Dustlight — Phase 1 go/no-go</h1>",
        f"<p class='dim'>Generated by <code>fo2hd report</code>. Everything here was produced automatically from the game data: no manual art. {e(notes.get('generated', ''))}</p>",
        "<div class='box'><b>Your decision:</b> go / no-go / go-with-changes on the HD half of the project (PLAN.md §5, P1.10).",
        "<br><b>Also open for you:</b><ul>",
    ]
    for item in notes.get("decisions", []):
        parts.append(f"<li>{item}</li>")
    parts.append("</ul></div>")

    parts.append("<h2>Benchmark scenes at 4×</h2><p>Drag across each image. Left of the line: the original game, pixel-doubled 4×. Right: the selected HD version. "
                 "<b>HD, original light</b> swaps only the art (same light as the original). <b>HD lit</b> adds the new lighting: direction from normal maps, colored lights, shadows, a softer highlight rolloff, darker blue nights.</p>")
    for scene, info in compose.items():
        title = SCENE_TITLES.get(scene, scene)
        eq = info.get("original_equivalent", {})
        parts.append(f"<h3>{e(title)}</h3>")
        parts.append(
            f"<div class='cmp' id='c_{scene}'><img src='img/{scene}_original.png' alt='original'>"
            f"<img class='top' src='img/{scene}_hd_lit.png' alt='HD'><div class='bar'></div>"
            f"<div class='tags'><span>original</span><span class='which'>HD lit</span></div>"
            f"<input type='range' min='0' max='100' value='50' oninput=\"this.parentNode.style.setProperty('--pos',this.value+'%')\"></div>"
        )
        parts.append(
            f"<div class='btns' data-scene='{scene}'>"
            f"<button class='on' data-img='hd_lit'>HD lit</button><button data-img='hd_orig'>HD, original light</button>"
            f"<button data-img='light'>light only</button><button data-img='normals'>normals</button><button data-img='orig_equiv'>original-equivalent check</button></div>"
        )
        parts.append(
            f"<p class='dim'>{info.get('hd_assets_used', 0)} HD assets, {len(info.get('fallback_assets', []))} fallbacks · "
            f"{info.get('lighting', {}).get('lights', 0)} light sources · ambient {info.get('lighting', {}).get('ambient', 0):.2f} · "
            f"original-equivalent check: mean |Δ| {eq.get('mean_abs', '?')} of 255, PSNR {eq.get('psnr', '?')} dB · rendered in {info.get('seconds', '?')} s (Python)</p>"
        )

    if anim:
        parts.append("<h2>Critter walk cycle at 4×</h2>")
        parts.append("<p>Tribal walk (<code>hmwarrab</code>), facing the camera. Left to right: original · HD frame by frame · HD stabilized with optical flow · HD from a 2× master.</p>")
        parts.append("<img src='img/walk_side_by_side.gif' style='max-width:100%;image-rendering:auto'>")
        parts.append("<p>Shimmer (flicker after motion compensation), relative to the original pixel art: 1.00 = as steady as the original; lower is calmer.</p><table><tr><th>variant</th><th class='num'>mean</th>" + "".join(f"<th class='num'>dir {r}</th>" for r in anim["rotations"]) + "</tr>")
        for name, value in anim["mean"].items():
            parts.append(f"<tr><td>{e(name)}</td><td class='num'>{value:.2f}</td>" + "".join(f"<td class='num'>{anim['rotations'][r][name]:.2f}</td>" for r in anim["rotations"]) + "</tr>")
        parts.append("</table>")

    parts.append("<h2>Upscaler pick</h2>")
    parts.append(f"<p>{notes.get('model_pick', '')} Full contact sheet: <a href='../bakeoff/index.html' style='color:var(--accent)'>bake-off</a>.</p>")
    if bakeoff:
        parts.append("<table><tr><th>model</th><th class='num'>speed (Mpx/s, tiny sprites)</th></tr>")
        for name, m in bakeoff.get("models", {}).items():
            parts.append(f"<tr><td>{e(name)}</td><td class='num'>{m['mpx_per_s']:.2f}</td></tr>")
        parts.append("</table>")

    parts.append("<h2>Checks</h2><table><tr><th>check</th><th>result</th></tr>")
    for scene, diff, draws in replay_rows:
        cls = "ok" if diff == 0 else "bad"
        parts.append(f"<tr><td>replay test: {e(scene)} ({draws} draws)</td><td class='{cls}'>{diff} px differ</td></tr>")
    for name, result in notes.get("checks", {}).items():
        parts.append(f"<tr><td>{e(name)}</td><td>{e(result)}</td></tr>")
    parts.append("</table>")

    parts.append("<h2>Throughput and full-game projection</h2>")
    if hd_run:
        fps_hour = hd_run["frames"] / max(hd_run["wall_seconds"], 1e-6) * 3600
        parts.append(f"<p>HD asset stage (upscale + maps), sample set: {hd_run['frames']} frames in {hd_run['wall_seconds']:.0f} s → <b>{fps_hour:,.0f} frames/hour</b> on the RTX 5060 Ti, one sprite at a time.</p>")
        if art:
            total_frames = sum(v["frames"] for v in art.values())
            total_px = sum(v["pixels"] for v in art.values())
            hours = total_frames / fps_hour
            parts.append(f"<p>The whole game has <b>{total_frames:,} frames / {total_px / 1e6:,.0f} Mpx</b> of art. At the same rate that is <b>about {hours:.0f} hours</b> for one full pass.</p>")
            parts.append("<table><tr><th>folder</th><th class='num'>files</th><th class='num'>frames</th><th class='num'>Mpx</th><th class='num'>share</th></tr>")
            for folder, v in sorted(art.items(), key=lambda kv: -kv[1]["pixels"]):
                parts.append(f"<tr><td>{e(folder)}</td><td class='num'>{v['files']:,}</td><td class='num'>{v['frames']:,}</td><td class='num'>{v['pixels'] / 1e6:,.1f}</td><td class='num'>{v['pixels'] / total_px:.0%}</td></tr>")
            parts.append("</table>")
    for line in notes.get("throughput", []):
        parts.append(f"<p>{line}</p>")

    parts.append("<h2>Failure cases and known gaps</h2><ul>")
    for item in notes.get("failures", []):
        parts.append(f"<li>{item}</li>")
    parts.append("</ul>")
    parts.append("<h2>What happens next</h2><ul>")
    for item in notes.get("next", []):
        parts.append(f"<li>{item}</li>")
    parts.append("</ul>")

    parts.append(
        "<script>document.querySelectorAll('.btns').forEach(b=>b.addEventListener('click',ev=>{const t=ev.target;if(!t.dataset.img)return;"
        "const s=b.dataset.scene,c=document.getElementById('c_'+s);c.querySelector('img.top').src='img/'+s+'_'+t.dataset.img+'.png';"
        "c.querySelector('.which').textContent=t.textContent;b.querySelectorAll('button').forEach(x=>x.classList.toggle('on',x===t));}));</script>"
    )
    parts.append("</body></html>")
    (out / "index.html").write_text("\n".join(parts), encoding="utf-8")
    return out / "index.html"
